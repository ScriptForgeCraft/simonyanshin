export const normalizeContactIcons = () => {
  const sprite = document.querySelector('.svg-sprite')
  if (!sprite) return

  Object.entries(contactIcons).forEach(([id, icon]) => {
    let symbol = sprite.querySelector(`#${id}`)
    if (!symbol) {
      symbol = document.createElementNS(svgNamespace, 'symbol')
      symbol.id = id
      sprite.append(symbol)
    }

    symbol.setAttribute('viewBox', icon.viewBox)
    symbol.replaceChildren()

    const path = document.createElementNS(svgNamespace, 'path')
    path.setAttribute('d', icon.path)
    symbol.append(path)
  })
}
